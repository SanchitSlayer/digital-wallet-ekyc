import base64
import hashlib
import hmac
import io
import json
from datetime import UTC, datetime, timedelta

import qrcode
from fastapi import HTTPException, status
from sqlalchemy.orm import Session

from app.auth.models import User
from app.core.config import settings
from app.payments.schemas import PaymentPreviewResponse, PaymentQrResponse, QrPayload
from app.wallet import service as wallet_service
from app.wallet.models import Transfer


def _b64url(data: bytes) -> str:
    return base64.urlsafe_b64encode(data).rstrip(b"=").decode()


def _b64url_decode(text: str) -> bytes:
    return base64.urlsafe_b64decode(text + "=" * (-len(text) % 4))


def _sign(encoded_payload: str) -> str:
    return _b64url(hmac.new(settings.qr_signing_key.encode(), encoded_payload.encode(), hashlib.sha256).digest())


def create_payment_qr(db: Session, user: User, amount_paise: int | None) -> PaymentQrResponse:
    wallet = wallet_service.get_active_wallet(db, user)
    expires_at = datetime.now(UTC).replace(microsecond=0) + timedelta(minutes=settings.qr_expire_minutes)
    payload = QrPayload(wallet_id=wallet.id, amount_paise=amount_paise, expires_at=expires_at)
    encoded_payload = _b64url(payload.model_dump_json().encode())
    qr_text = f"{encoded_payload}.{_sign(encoded_payload)}"

    png = io.BytesIO()
    qrcode.make(qr_text).save(png)
    return PaymentQrResponse(
        qr_payload=qr_text,
        qr_png_base64=base64.b64encode(png.getvalue()).decode(),
        wallet_id=wallet.id,
        amount_paise=amount_paise,
        expires_at=expires_at,
    )


def _verify_qr(qr_text: str) -> QrPayload:
    encoded_payload, separator, signature = qr_text.strip().partition(".")
    if not separator:
        raise HTTPException(
            status.HTTP_400_BAD_REQUEST, "Invalid payment QR: this is not a payment code generated by this app"
        )
    # compare_digest takes the same time however many leading characters match, so response timing cannot be
    # used to guess a valid signature one character at a time.
    if not hmac.compare_digest(signature, _sign(encoded_payload)):
        raise HTTPException(
            status.HTTP_400_BAD_REQUEST,
            "Invalid payment QR: the signature does not match, so the code was altered or not issued by this app",
        )
    payload = QrPayload.model_validate_json(_b64url_decode(encoded_payload))
    if payload.expires_at <= datetime.now(UTC):
        raise HTTPException(
            status.HTTP_410_GONE,
            f"Payment QR expired at {payload.expires_at.isoformat()}, ask the receiver to generate a new one",
        )
    return payload


def preview_payment(db: Session, payer: User, qr_text: str) -> PaymentPreviewResponse:
    wallet_service.get_active_wallet(db, payer)
    payload = _verify_qr(qr_text)
    receiver = wallet_service.get_wallet_or_404(db, payload.wallet_id)
    return PaymentPreviewResponse(
        receiver_wallet_id=receiver.id,
        receiver_name=receiver.user.full_name,
        amount_paise=payload.amount_paise,
        expires_at=payload.expires_at,
    )


def pay_with_qr(
    db: Session, payer: User, qr_text: str, amount_paise: int | None, idempotency_key: str
) -> Transfer:
    payload = _verify_qr(qr_text)
    if payload.amount_paise is not None and amount_paise not in (None, payload.amount_paise):
        raise HTTPException(
            status.HTTP_422_UNPROCESSABLE_CONTENT,
            f"Payment failed: this QR requests exactly {wallet_service.format_rupees(payload.amount_paise)}, "
            "the amount cannot be changed",
        )
    final_amount = payload.amount_paise or amount_paise
    if final_amount is None:
        raise HTTPException(
            status.HTTP_422_UNPROCESSABLE_CONTENT, "Payment failed: this QR has no amount, enter the amount to pay"
        )
    return wallet_service.transfer(db, payer, payload.wallet_id, final_amount, idempotency_key)
